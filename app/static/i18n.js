let LANG = "en";
function setLang(code) { LANG = STRINGS[code] ? code : "en"; document.documentElement.lang = LANG; }
function t(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
